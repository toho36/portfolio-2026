import { afterEach, describe, expect, it, vi } from 'vitest'
import { createDominantMotion } from '../shared/landingMotion'
import { createPlayback, READ_MS } from './playback'

afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals() })

describe('P1 playback', () => {
  it('starts static, pauses, resumes, finishes and replays with a full read interval', () => {
    vi.useFakeTimers()
    const coordinator = createDominantMotion()
    const player = createPlayback(coordinator, vi.fn())
    expect(player.state()).toEqual({ step: 0, status: 'idle', transitioning: false })
    player.play()
    vi.advanceTimersByTime(READ_MS - 1)
    expect(player.state().step).toBe(0)
    player.pause()
    vi.advanceTimersByTime(20000)
    expect(player.state().status).toBe('paused')
    player.play()
    vi.advanceTimersByTime(READ_MS)
    expect(player.state()).toEqual({ step: 1, status: 'playing', transitioning: true })
    vi.advanceTimersByTime(240)
    expect(player.state().transitioning).toBe(false)
    vi.advanceTimersByTime((READ_MS + 240) * 2 + READ_MS)
    expect(player.state()).toEqual({ step: 3, status: 'done', transitioning: false })
    expect(vi.getTimerCount()).toBe(0)
    expect(coordinator.currentId()).toBeUndefined()
    player.play()
    expect(player.state()).toEqual({ step: 0, status: 'playing', transitioning: false })
    player.dispose(); coordinator.dispose()
  })
  it('direct selection stops playback; another owner cancels transitions and timers', () => {
    vi.useFakeTimers()
    const coordinator = createDominantMotion()
    const player = createPlayback(coordinator, vi.fn())
    player.play(); player.select(2)
    expect(player.state()).toEqual({ step: 2, status: 'idle', transitioning: true })
    coordinator.start('index', vi.fn())
    expect(player.state().transitioning).toBe(false)
    expect(vi.getTimerCount()).toBe(0)
    player.play()
    coordinator.start('switch', vi.fn())
    expect(player.state().status).toBe('paused')
    expect(vi.getTimerCount()).toBe(0)
    player.dispose(); coordinator.dispose()
  })
  it('hidden/offscreen playback pauses and never resumes automatically', () => {
    vi.useFakeTimers()
    const doc = Object.assign(new EventTarget(), { hidden: false })
    vi.stubGlobal('document', doc)
    const coordinator = createDominantMotion()
    const player = createPlayback(coordinator, vi.fn())
    player.play(); doc.hidden = true; doc.dispatchEvent(new Event('visibilitychange'))
    expect(player.state().status).toBe('paused')
    player.play(); expect(player.state().status).toBe('paused')
    doc.hidden = false; doc.dispatchEvent(new Event('visibilitychange'))
    expect(player.state().status).toBe('paused')
    player.setVisible(false); player.play()
    expect(vi.getTimerCount()).toBe(0)
    player.setVisible(true); expect(player.state().status).toBe('paused')
    player.play(); expect(player.state().status).toBe('playing')
    player.dispose(); coordinator.dispose()
  })
  it('settles an interrupted transition and clears all timers on unmount', () => {
    vi.useFakeTimers()
    const coordinator = createDominantMotion()
    const player = createPlayback(coordinator, vi.fn())
    player.play(); vi.advanceTimersByTime(READ_MS + 100)
    expect(player.state().transitioning).toBe(true)
    player.setVisible(false)
    expect(player.state()).toEqual({ step: 1, status: 'paused', transitioning: false })
    expect(vi.getTimerCount()).toBe(0)
    player.setVisible(true); player.select(3); player.select(1)
    vi.advanceTimersByTime(240)
    expect(player.state()).toEqual({ step: 1, status: 'idle', transitioning: false })
    expect(vi.getTimerCount()).toBe(0)
    player.play(); player.dispose()
    expect(vi.getTimerCount()).toBe(0)
    expect(coordinator.currentId()).toBeUndefined()
    coordinator.dispose()
  })
  it('reduced motion switches complete states and creates no transition timer', () => {
    vi.useFakeTimers()
    vi.stubGlobal('window', { matchMedia: () => ({ matches: true }) })
    const coordinator = createDominantMotion()
    const player = createPlayback(coordinator, vi.fn())
    player.select(1)
    expect(player.state().transitioning).toBe(false)
    expect(vi.getTimerCount()).toBe(0)
    player.play(); vi.advanceTimersByTime(READ_MS)
    expect(player.state()).toEqual({ step: 2, status: 'playing', transitioning: false })
    player.dispose(); expect(vi.getTimerCount()).toBe(0); coordinator.dispose()
  })
})
